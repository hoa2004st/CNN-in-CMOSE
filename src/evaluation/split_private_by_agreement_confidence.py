"""Split private clips into a 2x2 matrix of agreement/confidence groups."""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Split private clips into High/Low Agreement x High/Low Confidence groups.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--input_csv",
        default="outputs/domain_shift_analysis/model_agreement_per_clip.csv",
        help="Per-clip agreement table generated by run_domain_shift_analysis.py",
    )
    parser.add_argument(
        "--output_dir",
        default="outputs/domain_shift_analysis",
        help="Directory to write split results.",
    )
    parser.add_argument(
        "--agreement_threshold",
        type=float,
        default=None,
        help="Custom threshold for agreement_rate. If omitted, median is used.",
    )
    parser.add_argument(
        "--confidence_threshold",
        type=float,
        default=None,
        help="Custom threshold for mean_confidence. If omitted, median is used.",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    input_path = Path(args.input_csv)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    df = pd.read_csv(input_path)
    required = {"clip_id", "agreement_rate", "mean_confidence"}
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(f"Missing required column(s) in {input_path}: {missing}")

    agreement_threshold = (
        float(args.agreement_threshold)
        if args.agreement_threshold is not None
        else float(df["agreement_rate"].median())
    )
    confidence_threshold = (
        float(args.confidence_threshold)
        if args.confidence_threshold is not None
        else float(df["mean_confidence"].median())
    )

    out = df.copy()
    out["agreement_level"] = out["agreement_rate"].apply(
        lambda value: "High Agreement" if float(value) >= agreement_threshold else "Low Agreement"
    )
    out["confidence_level"] = out["mean_confidence"].apply(
        lambda value: "High Confidence" if float(value) >= confidence_threshold else "Low Confidence"
    )
    out["group_2x2"] = out["agreement_level"] + " | " + out["confidence_level"]

    matrix = (
        out.pivot_table(
            index="agreement_level",
            columns="confidence_level",
            values="clip_id",
            aggfunc="count",
            fill_value=0,
        )
        .reindex(index=["High Agreement", "Low Agreement"], columns=["High Confidence", "Low Confidence"])
        .fillna(0)
        .astype(int)
    )
    matrix_ratio = (matrix / max(int(len(out)), 1)).round(6)

    out_path = output_dir / "private_clips_agreement_confidence_split.csv"
    matrix_path = output_dir / "agreement_confidence_2x2_counts.csv"
    ratio_path = output_dir / "agreement_confidence_2x2_ratio.csv"
    summary_path = output_dir / "agreement_confidence_2x2_summary.md"
    heatmap_path = output_dir / "agreement_confidence_2x2_heatmap.png"

    out.to_csv(out_path, index=False)
    matrix.to_csv(matrix_path)
    matrix_ratio.to_csv(ratio_path)
    plot_2x2_heatmap(matrix, heatmap_path)

    summary_lines = [
        "# Private Dataset 2x2 Split",
        "",
        f"- Total clips: {len(out)}",
        f"- Agreement threshold: {agreement_threshold:.6f}",
        f"- Confidence threshold: {confidence_threshold:.6f}",
        "",
        "## 2x2 Count Matrix",
        "",
        matrix.to_markdown(),
        "",
        "## 2x2 Ratio Matrix",
        "",
        matrix_ratio.to_markdown(),
        "",
        "Group labels:",
        "- `High/Low Agreement` is based on `agreement_rate`.",
        "- `High/Low Confidence` is based on `mean_confidence`.",
    ]
    summary_path.write_text("\n".join(summary_lines) + "\n", encoding="utf-8")

    print(f"Saved split table: {out_path}")
    print(f"Saved 2x2 count matrix: {matrix_path}")
    print(f"Saved 2x2 ratio matrix: {ratio_path}")
    print(f"Saved summary: {summary_path}")
    print(f"Saved heatmap: {heatmap_path}")


def plot_2x2_heatmap(matrix: pd.DataFrame, output_path: Path) -> None:
    fig, ax = plt.subplots(figsize=(5.6, 4.6))
    image = ax.imshow(matrix.values, cmap="YlGnBu", aspect="equal")
    ax.set_title("Private Clips: Agreement x Confidence (Count)")
    ax.set_xlabel("Confidence")
    ax.set_ylabel("Agreement")
    ax.set_xticks([0, 1], labels=list(matrix.columns))
    ax.set_yticks([0, 1], labels=list(matrix.index))
    for i in range(matrix.shape[0]):
        for j in range(matrix.shape[1]):
            value = int(matrix.iloc[i, j])
            ax.text(j, i, str(value), ha="center", va="center", color="black", fontsize=12)
    fig.colorbar(image, ax=ax, fraction=0.05, pad=0.04, label="Clip count")
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)


if __name__ == "__main__":
    main()
